#!/usr/bin/env python3
"""Golden fixture for the media web-frame format (EG-7).

Why this file exists at all, and why it is Python rather than a Rust helper:
the fixture must be an **independent** implementation of the layout. A fixture
generated by the encoder under test asserts only that the encoder is
self-consistent; one written from the documented table can disagree with it,
and that disagreement is the whole point.

The layout is documented in three places that must not drift:
  * herdr-web/src/media-framing.ts   (the consumer, and the source of truth)
  * src/media/web_frame.rs           (the producer)
  * this file                        (the referee)

    offset  size  field
         0     1  magic   'M' (0x4D)
         1     1  version 1
         2     1  kind    0=chunk 1=open 2=close 3=timesync
         3     1  flags
         4     4  stream_id   u32 LE
         8     8  seq         u64 LE
        16     8  pts_us      u64 LE
        24     4  payload_len u32 LE
        28     n  payload

Control payloads (open, close) are compact UTF-8 JSON and their **key order is
load-bearing**, because the assertion is byte-exact on both sides. That is a
deliberate trade: an order change is a wire change, and a wire change should
turn a test red rather than pass silently on one side.

Usage:
    python3 scripts/media_web_frame_fixture.py --write   # regenerate
    python3 scripts/media_web_frame_fixture.py --check   # verify committed bytes
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import struct
import sys

MAGIC = 0x4D
VERSION = 1
HEADER_BYTES = 28

KIND_CHUNK = 0
KIND_OPEN = 1
KIND_CLOSE = 2
KIND_TIMESYNC = 3

ROOT = pathlib.Path(__file__).resolve().parent.parent
BIN_PATH = ROOT / "tests" / "fixtures" / "media_web_frames.bin"
JSON_PATH = ROOT / "tests" / "fixtures" / "media_web_frames.json"


def compact_json(pairs: list[tuple[str, object]]) -> bytes:
    """Compact JSON with the given key order preserved.

    `dict` preserves insertion order in every Python this repository runs on,
    and `separators` removes the spaces `json.dumps` would otherwise add — the
    Rust side emits neither.
    """
    return json.dumps(dict(pairs), separators=(",", ":")).encode("utf-8")


def encode_frame(kind: int, flags: int, stream_id: int, seq: int, pts_us: int,
                 payload: bytes) -> bytes:
    header = struct.pack(
        "<BBBBIQQI", MAGIC, VERSION, kind, flags, stream_id, seq, pts_us, len(payload)
    )
    assert len(header) == HEADER_BYTES, f"header is {len(header)} bytes, not {HEADER_BYTES}"
    return header + payload


# The stream the fixture describes. Fixed numbers, no clock, no randomness:
# a fixture that is not reproducible is not a fixture.
STREAM_ID = 7

OPEN_PAYLOAD = compact_json([
    ("pane_id", "pane-fixture-1"),
    ("codec", "opus"),
    ("sample_rate_hz", 48000),
    ("channels", 2),
    ("target_latency_us", 100000),
])

# Deliberately not all-identical bytes and deliberately two different lengths:
# an offset or an endianness mistake shows up, and a decoder that reads one
# length and applies it to both frames is caught.
CHUNK_ONE = bytes([0x01, 0x02, 0x03, 0x04, 0xFC, 0xFD, 0xFE, 0xFF])
CHUNK_TWO = bytes([0xA0, 0xB1, 0xC2, 0xD3, 0xE4])

CLOSE_PAYLOAD = compact_json([
    ("reason", "ended"),
    ("detail", ""),
])

FRAMES = [
    # name, kind, flags, seq, pts_us, payload
    ("open", KIND_OPEN, 0, 0, 1_000_000, OPEN_PAYLOAD),
    ("chunk-1", KIND_CHUNK, 0, 1, 1_000_000, CHUNK_ONE),
    ("chunk-2", KIND_CHUNK, 0, 2, 1_020_000, CHUNK_TWO),
    ("close", KIND_CLOSE, 0, 3, 1_040_000, CLOSE_PAYLOAD),
]


def build() -> tuple[bytes, dict]:
    blob = b""
    described = []
    for name, kind, flags, seq, pts_us, payload in FRAMES:
        offset = len(blob)
        blob += encode_frame(kind, flags, STREAM_ID, seq, pts_us, payload)
        described.append({
            "name": name,
            "offset": offset,
            "kind": kind,
            "flags": flags,
            "stream_id": STREAM_ID,
            "seq": seq,
            "pts_us": pts_us,
            "payload_len": len(payload),
            "payload_hex": payload.hex(),
        })
    # The sha256 pin deliberately does NOT live here. It belongs in the two
    # test files that assert it — one per language — because a hash stored
    # beside the data it hashes travels with a hand-edited copy and agrees with
    # it. A third copy is a third thing to drift.
    manifest = {
        "note": (
            "Golden frames for the media web-frame format. Generated by "
            "scripts/media_web_frame_fixture.py from the documented layout, not "
            "by either implementation. Both the Rust encoder and the TypeScript "
            "decoder assert against these bytes; neither side can move alone. "
            "Headers and chunk payloads are compared BYTE-EXACT: that is a "
            "binary contract. Control payloads (open, close) are compared "
            "FIELD-EXACT after parsing, because their contract is the fields, "
            "not the key order -- a byte comparison there would turn a "
            "serialiser's ordering choice into a false failure."
        ),
        "header_bytes": HEADER_BYTES,
        "magic": MAGIC,
        "version": VERSION,
        "total_bytes": len(blob),
        "frames": described,
    }
    return blob, manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the fixture")
    group.add_argument("--check", action="store_true", help="verify the committed fixture")
    args = parser.parse_args()

    blob, manifest = build()
    manifest_bytes = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")

    if args.write:
        BIN_PATH.parent.mkdir(parents=True, exist_ok=True)
        BIN_PATH.write_bytes(blob)
        JSON_PATH.write_bytes(manifest_bytes)
        print(f"wrote {BIN_PATH.relative_to(ROOT)} ({len(blob)} bytes)")
        print(f"wrote {JSON_PATH.relative_to(ROOT)}")
        print(f"sha256 {hashlib.sha256(blob).hexdigest()}  <- pin this in the tests")
        return 0

    failures = []
    if not BIN_PATH.exists():
        failures.append(f"missing {BIN_PATH.relative_to(ROOT)}")
    elif BIN_PATH.read_bytes() != blob:
        failures.append(
            f"{BIN_PATH.relative_to(ROOT)} differs from the generator — the fixture was "
            "edited by hand or the layout changed"
        )
    if not JSON_PATH.exists():
        failures.append(f"missing {JSON_PATH.relative_to(ROOT)}")
    elif JSON_PATH.read_bytes() != manifest_bytes:
        failures.append(f"{JSON_PATH.relative_to(ROOT)} differs from the generator")

    if failures:
        for line in failures:
            print(f"FAIL: {line}", file=sys.stderr)
        return 1
    print(f"fixture OK — {len(blob)} bytes, sha256 {hashlib.sha256(blob).hexdigest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
